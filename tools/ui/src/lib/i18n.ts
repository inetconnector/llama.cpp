function detectNavigatorLocale(): SupportedLocale {
	if (!browser) return 'en';

	const urlLocale = new URL(window.location.href).searchParams.get('lang');
	if (urlLocale) {
		return normalizeLocale(urlLocale);
	}

	const browserLocale =
		window.navigator.language || window.navigator.languages?.find((entry) => !!entry) || 'en';
	return normalizeLocale(browserLocale);
}

export function normalizeLocale(rawLocale?: string | null): SupportedLocale {
	if (!rawLocale) return 'en';

	const normalized = rawLocale.trim().replaceAll('_', '-');
	if (!normalized) return 'en';

	const exact = SUPPORTED_LOCALES.find(
		(locale) => locale.toLowerCase() === normalized.toLowerCase()
	);
	if (exact) return exact;

	const lower = normalized.toLowerCase();
	const base = lower.split('-')[0];

	switch (base) {
		case 'de':
			return 'de';
		case 'es':
			return 'es';
		case 'fr':
			return 'fr';
		case 'it':
			return 'it';
		case 'nl':
			return 'nl';
		case 'pl':
			return 'pl';
		case 'pt':
			return 'pt-BR';
		case 'tr':
			return 'tr';
		default:
			return 'en';
	}
}

export const currentLocale: SupportedLocale = detectNavigatorLocale();

export function applyDocumentLocale(locale: SupportedLocale = currentLocale): void {
	if (!browser || typeof document === 'undefined') return;

	document.documentElement.lang = locale;
	document.documentElement.dir = RTL_LOCALES.has(locale.split('-')[0]) ? 'rtl' : 'ltr';
	document.documentElement.dataset.locale = locale;
}

function interpolate(template: string, values?: TemplateValues): string {
	if (!values) return template;

	return template.replace(/{{\s*([\w.-]+)\s*}}/g, (_match, key: string) => {
		const value = values[key];
		return value === undefined || value === null ? '' : String(value);
	});
}

export function t(source: string, values?: TemplateValues, locale: SupportedLocale = currentLocale): string {
	const translated = TRANSLATIONS[locale]?.[source] ?? source;
	return interpolate(translated, values);
}

export function pluralize(
	count: number,
	forms: PluralForms,
	locale: SupportedLocale = currentLocale
): string {
	const rule = new Intl.PluralRules(locale).select(count);
	return forms[rule] ?? forms.other ?? forms.one ?? '';
}
